  app.get(
    "/api/v1/projects/:id/coverage-matrix",
    { preHandler: authenticate, schema: { tags: ["coverage"] } },
    async (request) => {
      const { id } = IdParams.parse(request.params);
      const access = await projectAccess(request, id);
      const requirements = await db.requirement.findMany({
        where: { projectId: id, workspaceId: access.workspaceId, deletedAt: null },
        include: {
          testCases: {
            where: { deletedAt: null },
            include: {
              testResults: {
                orderBy: { createdAt: "desc" },
                take: 1,
                select: { outcome: true, createdAt: true, testRunId: true },
              },
            },
          },
        },
        orderBy: { key: "asc" },
      });
      const matrix = requirements.map((requirement) => {
        const outcomes = requirement.testCases.flatMap((testCase) =>
          testCase.testResults.map((result) => result.outcome),
        );
        const status =
          requirement.testCases.length === 0
            ? "NOT_COVERED"
            : outcomes.includes("FAILED")
              ? "COVERED_FAILING"
              : outcomes.includes("PASSED")
                ? "COVERED_PASSING"
                : "COVERED_NOT_EXECUTED";
        return {
          requirement: {
            id: requirement.id,
            key: requirement.key,
            title: requirement.title,
            riskLevel: requirement.riskLevel,
          },
          status,
          testCases: requirement.testCases.map((testCase) => ({
            id: testCase.id,
            key: testCase.key,
            title: testCase.title,
            status: testCase.status,
            latestResult: testCase.testResults[0] ?? null,
          })),
        };
      });
      return {
        matrix,
        summary: {
          requirements: matrix.length,
          covered: matrix.filter((item) => item.status !== "NOT_COVERED").length,
        },
      };
    },
  );

