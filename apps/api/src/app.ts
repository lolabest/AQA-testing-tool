  async function decideHealing(
    request: FastifyRequest,
    decisionFromRoute?: "APPROVE" | "REJECT",
  ) {
    const { id } = IdParams.parse(request.params);
    const input = HealingDecisionInput.parse(request.body ?? {});
    const decision =
      decisionFromRoute ??
      ("decision" in input ? input.decision : undefined);
    if (!decision) {
      throw new ApiError(400, "DECISION_REQUIRED", "A healing decision is required");
    }
    const proposal = await db.healingProposal.findFirst({
      where: {
        id,
        project: {
          workspace: {
            memberships: {
              some: { userId: auth(request).userId, deletedAt: null },
            },
          },
        },
      },
    });
    if (!proposal) {
      throw new ApiError(404, "NOT_FOUND", "Healing proposal was not found");
    }
    await projectAccess(request, proposal.projectId, "healing:approve");
    if (proposal.status !== "PENDING") {
      throw new ApiError(409, "ALREADY_REVIEWED", "Proposal was already reviewed");
    }
    const note = "note" in input ? input.note : undefined;
    const updated = await db.healingProposal.update({
      where: { id },
      data: {
        status: decision === "APPROVE" ? "APPROVED" : "REJECTED",
        reviewComment: note,
        reviewedAt: new Date(),
        reviewedById: auth(request).userId,
        version: { increment: 1 },
      },
    });
    await audit(
      request,
      proposal.workspaceId,
      `healing.${decision.toLowerCase()}`,
      "HealingProposal",
      id,
      { note },
    );
    return updated;
  }

